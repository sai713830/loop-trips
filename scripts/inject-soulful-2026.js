const U = (id) => `U("${id}")`;

function pkg(o) {
  const cols = o.columns || ["Price"];
  const rows = o.rows
    .map((r) => {
      const vals = Array.isArray(r.values) ? r.values : [r];
      return `      { pax: ${r.pax}, values: [${vals.join(", ")}] }`;
    })
    .join(",\n");
  const gal = (o.gallery || []).map((g) => U(g)).join(", ");
  const highs = (o.highlights || []).map((h) => JSON.stringify(h)).join(", ");
  const itin = (o.itinerary || [])
    .map((d) => `      { day: ${JSON.stringify(d.day)}, title: ${JSON.stringify(d.title)}, text: ${JSON.stringify(d.text)} }`)
    .join(",\n");
  const locs = o.locations.map((l) => JSON.stringify(l)).join(", ");
  return `  {
    id: ${JSON.stringify(o.id)},
    title: ${JSON.stringify(o.title)},
    country: ${JSON.stringify(o.country)},
    locations: [${locs}],
    duration: ${JSON.stringify(o.duration)},
    days: ${o.days},
    nights: ${o.nights},
    pax: 2,
    price: ${o.price},
    currency: "INR",
    region: ${JSON.stringify(o.region || "India")},
    theme: ${JSON.stringify(o.theme || "Escape")},
    status: "Open",
    departure: ${JSON.stringify(o.departure || "")},
    image: ${U(o.image)},
    gallery: [${gal}],
    blurb: ${JSON.stringify(o.blurb)},
    story: ${JSON.stringify(o.story)},
    highlights: [${highs}],
    inclusions: STAYS_IN,
    itinerary: [
${itin}
    ],
    bestTime: ${JSON.stringify(o.bestTime || "October – March")},
    priceTable: {
      label: ${JSON.stringify(o.priceLabel)},
      columns: ${JSON.stringify(cols)},
      rows: [
${rows}
      ],
    },
  }`;
}

