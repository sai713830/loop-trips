// Update matching existing packages with new starting prices + tables
function updateExisting(id, price, priceTableObj) {
  const idRe = new RegExp(`(id: "${id}"[\\s\\S]*?price: )\\d+`);
  if (!idRe.test(src)) {
    console.warn("skip update, not found:", id);
    return;
  }
  src = src.replace(idRe, `$1${price}`);
  const cols = JSON.stringify(priceTableObj.columns);
  const rows = priceTableObj.rows
    .map((r) => `      { pax: ${r.pax}, values: [${r.values.join(", ")}] }`)
    .join(`,${nl}`);
  const pt = `    priceTable: {${nl}      label: ${JSON.stringify(priceTableObj.label)},${nl}      columns: ${cols},${nl}      rows: [${nl}${rows}${nl}      ],${nl}    },${nl}`;
  const blockRe = new RegExp(
    `(id: "${id}"[\\s\\S]*?bestTime: "[^"]*",)${nl}(?:    priceTable: \\{[\\s\\S]*?\\},${nl})?(  \\},)`
  );
  if (!blockRe.test(src)) {
    console.warn("skip priceTable inject, structure mismatch:", id);
    return;
  }
  src = src.replace(blockRe, `$1${nl}${pt}$2`);
  console.log("updated", id, "->", price);
}

